StopZ80:
	move	sr,(saved_sr).w
	move	#$2700,sr
	move.w	#$100,(Z80_BUS).l

loc_2022E6:
	btst	#0,(Z80_BUS).l
	bne.s	loc_2022E6
	rts

; ------------------------------------------------------------------------------

StartZ80:
	move.w	#0,(Z80_BUS).l
	move	(saved_sr).w,sr
	rts

; ------------------------------------------------------------------------------

LoadDummyZ80:
	move.w	#$100,(Z80_RESET).l
	jsr	StopZ80(pc)
	lea	(Z80_RAM).l,a1
	move.b	#$F3,(a1)+
	move.b	#$F3,(a1)+
	move.b	#$C3,(a1)+
	move.b	#0,(a1)+
	move.b	#0,(a1)+
	move.w	#0,(Z80_RESET).l
	ror.b	#8,d0
	move.w	#$100,(Z80_RESET).l
	jmp	StartZ80(pc)

