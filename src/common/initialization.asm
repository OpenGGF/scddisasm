; ------------------------------------------------------------------------------
; Sonic CD Disassembly
; ------------------------------------------------------------------------------

; ------------------------------------------------------------------------------
; MMD header
; ------------------------------------------------------------------------------

	mmd 0, WORD_RAM_2M, 0, MmdEntry, MmdHBlank, MmdVBlank

; ------------------------------------------------------------------------------
; MMD entry point
; ------------------------------------------------------------------------------

MmdEntry:
	jmp	Entry

; ------------------------------------------------------------------------------
; MMD exception
; ------------------------------------------------------------------------------

MmdException:
	jmp	Exception

; ------------------------------------------------------------------------------
; MMD H-BLANK interrupt
; ------------------------------------------------------------------------------

MmdHBlank:
	jmp	HBlank

; ------------------------------------------------------------------------------
; MMD V-BLANK interrupt
; ------------------------------------------------------------------------------

MmdVBlank:
	jmp	VBlank

; ------------------------------------------------------------------------------
; Exception
; ------------------------------------------------------------------------------

Exception:
	nop
	nop
	bra.s	Exception

; ------------------------------------------------------------------------------
; Entry point
; ------------------------------------------------------------------------------

Entry:
	btst	#6,IO_CTRL_3
	beq.s	.Initialize
	cmpi.l	#"init",initialized
	beq.w	.StartStage

.Initialize:
	lea	unk_buffer,a6
	moveq	#0,d7
	move.w	#$FF,d6
	move.w	#$7F,d6

.ClearBuffer:
	move.l	d7,(a6)+
	dbf	d6,.ClearBuffer

	move.b	IO_VERSION,d0
	andi.b	#$C0,d0
	move.b	d0,system_version
	move.l	#"init",initialized

.StartStage:
	bsr.w	InitVdp
	bsr.w	InitJoypads
	move.b	#0,game_mode

	move.b	game_mode,d0
	andi.w	#$1C,d0
	jmp	.GameModes(pc,d0.w)

; ------------------------------------------------------------------------------

.GameModes:
	bra.w	InitStage

; ------------------------------------------------------------------------------
